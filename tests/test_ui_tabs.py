"""Browser checks for the three input modes; uses the local demo on port 8002."""
from io import BytesIO
from openpyxl import Workbook
from playwright.sync_api import sync_playwright, expect


def test_tabs_preserve_input_and_auto_preview(tmp_path):
    with sync_playwright() as p:
        browser = p.chromium.launch(channel='chrome', headless=True)
        page = browser.new_page(viewport={'width': 1280, 'height': 900})
        errors = []
        page.on('pageerror', lambda error: errors.append(str(error)))
        page.goto('http://127.0.0.1:8002/')
        expect(page.get_by_role('tab')).to_have_count(3)
        page.locator('#text').fill('Giảng viên nhiệt tình.')
        page.get_by_role('tab', name='Danh sách phản hồi').click()
        expect(page.locator('#text')).not_to_be_visible()
        page.locator('#batch-text').fill('Giảng viên nhiệt tình.\nPhòng học nóng.')
        page.locator('#preview-paste').click()
        page.locator('#batch-run').click()
        expect(page.locator('#batch-summary')).to_contain_text('Thành công: 2', timeout=60000)
        page.get_by_role('tab', name='Một phản hồi', exact=True).click()
        expect(page.locator('#text')).to_have_value('Giảng viên nhiệt tình.')
        page.locator('#go').click()
        expect(page.locator('#out .res')).to_be_visible()
        page.get_by_role('tab', name='Nhập file', exact=True).click()
        expect(page.locator('#batch-text')).not_to_be_visible()
        book = Workbook()
        book.active.append(['Nội dung phản hồi'])
        book.active.append(['Phòng học sạch sẽ.'])
        stream = BytesIO()
        book.save(stream)
        page.locator('#batch-file').set_input_files({'name': 'input.xlsx', 'mimeType': 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet', 'buffer': stream.getvalue()})
        expect(page.locator('#batch-table tbody tr')).to_have_count(1)
        expect(page.locator('#batch-run')).to_be_enabled()
        expect(page.locator('#column-select')).not_to_be_visible()
        page.locator('#batch-run').click()
        expect(page.locator('#batch-summary')).to_contain_text('Thành công: 1', timeout=60000)
        page.get_by_role('tab', name='Nhập file', exact=True).focus()
        page.keyboard.press('Home')
        expect(page.get_by_role('tab', name='Một phản hồi', exact=True)).to_be_focused()
        page.locator('#text').fill('🙂'*5001)
        expect(page.locator('#go')).to_be_disabled()
        page.locator('#text').fill('Giảng viên nhiệt tình.')
        page.route('**/api/v3/predict', lambda route: route.fulfill(status=503, json={}))
        page.locator('#go').click()
        expect(page.locator('#out .error')).to_be_visible()
        expect(page.locator('#recheck')).to_be_visible()
        expect(page.locator('#text')).to_have_value('Giảng viên nhiệt tình.')
        page.unroute('**/api/v3/predict')
        page.locator('#recheck').click()
        expect(page.locator('#recheck')).not_to_be_visible()
        page.locator('#go').click()
        expect(page.locator('#out .res')).to_be_visible()
        page.get_by_role('tab', name='Nhập file', exact=True).click()
        expect(page.locator('#batch-summary')).to_contain_text('Thành công: 1')
        page.set_viewport_size({'width': 390, 'height': 844})
        assert page.evaluate('document.documentElement.scrollWidth <= innerWidth')
        page.screenshot(path=str(tmp_path/'ui-tabs-mobile.png'), full_page=True)
        page.set_viewport_size({'width': 1280, 'height': 900})
        page.screenshot(path=str(tmp_path/'ui-tabs-desktop.png'), full_page=True)
        assert not errors
        browser.close()
